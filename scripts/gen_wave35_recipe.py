#!/usr/bin/env python
"""Генератор рецепта рычага доли ветви внимания (журнал §96.6, полосы П86.1 §96.7).

Одно переменное — направление дозы по тензору linear_attn.out_proj.weight целиком:
слои 1, 2, 4 получают множитель 1,02, слои 17, 18, 21 — обратный 0,9803921568627451.
Суммарная доза по натуральным логарифмам: 3 * ln(1,02) + 3 * ln(1/1,02) = 0.

Слои выбраны по измеренному зонду, а не из руки
(runs/analysis/probe_w8_model.json, хвост генерации, gain_attn_tail по линейным слоям):
  усиливаются: слой 1 = 0,6595, слой 2 = 0,6531, слой 4 = 0,4062;
  приглушаются: слой 21 = 0,2218, слой 18 = 0,2511, слой 17 = 0,2655.
Слой 0 (gain_attn_tail 1,6740) исключён как выброс: его относительный вклад раздут
минимальным остаточным потоком первого блока, а не работой ветви.

Проверяемая гипотеза H59: принцип «усиливать ветвь там, где её относительный вклад в
хвосте выше» переносится с MLP-ветви (журнал §96.4: направление A лучше обращённого на
10 задач качества) на ветвь внимания. Решающий вторичный критерий — качество на
пересечении задач со строкой FINAL против w8: не хуже минус двух задач.

Рецепт: recipes/w86_attnshare_lever_on_w8.json
База сборки — контрольная точка w8_z_gate_mild_format, читается только на чтение.
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAME = "w86_attnshare_lever_on_w8"
TENSOR = "model.language_model.layers.*.linear_attn.out_proj.weight"
LAYERS_UP = [1, 2, 4]
LAYERS_DOWN = [17, 18, 21]
LAM_UP = 1.02
LAM_DOWN = 1.0 / LAM_UP
TENSOR_NUMEL = 1024 * 2048
BAND = "П86.1"
PLANNED_BAND = ("dev 58..68 / 88..98 / 0..8; search 138..158 / 222..244 / 8..22; "
                "combined 196..224 / 312..348 / 8..26")


def main():
    ops = [
        {
            "tensors": [TENSOR],
            "op": "scale",
            "lam": LAM_UP,
            "layers": LAYERS_UP,
            "note": "три линейных слоя с наибольшим относительным вкладом ветви внимания "
                    "в хвосте генерации (gain_attn_tail 0,6595 / 0,6531 / 0,4062)",
        },
        {
            "tensors": [TENSOR],
            "op": "scale",
            "lam": LAM_DOWN,
            "layers": LAYERS_DOWN,
            "note": "три слоя с наименьшим относительным вкладом (0,2218 / 0,2511 / 0,2655) "
                    "при большой абсолютной мощности ветви; слой 0 исключён как выброс",
        },
    ]
    dose = len(LAYERS_UP) * math.log(LAM_UP) + len(LAYERS_DOWN) * math.log(LAM_DOWN)
    recipe = {
        "name": NAME,
        "band": BAND,
        "hypothesis": "H59: принцип распределения мощности ветви по слоям, подтверждённый "
                      "для mlp.up_proj (направление A лучше обращённого на 10 задач качества "
                      "на пересечении со строкой FINAL), переносится на ветвь внимания: "
                      "усиление выхода linear_attn.out_proj в слоях с высоким относительным "
                      "вкладом хвоста (1, 2, 4) и приглушение слоёв с низким вкладом "
                      "(17, 18, 21) при нейтральной суммарной дозе держит качество не ниже "
                      "w8. Если и эта ось окажется ниже w8, принцип считается опровергнутым "
                      "для обеих ветвей, и поиск сужается до состава строк embed_tokens и "
                      "гейтов in_proj_z.",
        "expected_effect": "Сдвиг качества решения на dev и search без изменения профиля "
                           "строки FINAL; суммарная доза по натуральным логарифмам равна "
                           f"{dose:+.6f}, то есть ноль; меняется только относительная доля "
                           "между слоями. Ожидаемое изменение нормы тензора в каждом "
                           "задетом слое — порядка 2 % на значение; объём правки "
                           f"6 * 1024 * 2048 = {6 * TENSOR_NUMEL} значений. Полоса по "
                           "§96.7: " + PLANNED_BAND + ". Зачёт: combined математика не "
                           "ниже 218, извлечение не ниже 332, обрывы не больше 14, dev "
                           "математика не ниже 63. Провал: формат ниже 312 или математика "
                           "ниже 196. Решающий вторичный критерий: качество на пересечении "
                           "задач с FINAL против w8 не хуже минус двух задач. Официальный "
                           "набор из 1319 задач используется только для оценки и при выборе "
                           "ветки не использовался.",
        "ops": ops,
    }
    out = ROOT / "recipes" / f"{NAME}.json"
    if out.exists():
        raise SystemExit(f"файл уже существует, не перезаписываю: {out}")
    out.write_text(json.dumps(recipe, ensure_ascii=False, indent=1), encoding="utf-8")

    print("тип tensors:", "list" if all(isinstance(o["tensors"], list) for o in ops) else "не list")
    print(f"файл: {out.relative_to(ROOT)}, операций: {len(ops)}")
    print("слои на усиление:", LAYERS_UP, "| на приглушение:", LAYERS_DOWN)
    print(f"планируемых изменённых значений: {6 * TENSOR_NUMEL}")
    print(f"суммарная доза по логарифмам: {dose:+.9f}")
    print("полоса рецепта:", recipe["band"], "— сверена с журналом §96.7")


main()
