#!/usr/bin/env python
"""Рецепты волны 8. Гипотезы опираются только на замеры 250 search + 100 dev
и на послойные зонды активаций (runs/analysis/probe_*.json). Официальный test
(1319 задач) не читался и не используется. Все три варианта собираются ПОВЕРХ
контрольной точки w8_z_gate_mild_format; исходная модель и w8 не изменяются."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REC = ROOT / "recipes"
LIN = [l for l in range(24) if l not in (3, 7, 11, 15, 19, 23)]
FULLS = [3, 7, 11, 15, 19, 23]
PROBE = json.load(open(ROOT / "runs/analysis/probe_w8_model.json"))["layers"]

# головы z-конвейера w8 с |silu(z)| > 0,8 (замер: 29 голов в 13 слоях)
Z_HEADS = {l: [h for h, v in enumerate(PROBE[str(l)]["z_gate_head"]) if v > 0.8]
           for l in LIN if "z_gate_head" in PROBE[str(l)]}
Z_HEADS = {l: v for l, v in Z_HEADS.items() if v}
LATE_Z = [14, 16, 17, 18, 20, 21, 22]   # слои, где w8 опустил gain_attn на 4,1..7,3 %
EARLY_Z = [l for l in LIN if l not in LATE_Z]   # 11 слоёв, оставшихся после снятия дозы

assert len(Z_HEADS) == 13, Z_HEADS
assert sum(len(v) for v in Z_HEADS.values()) == 29


def head_ops(lam):
    ops = []
    for l in sorted(Z_HEADS):
        rows = [r for h in Z_HEADS[l] for r in range(h * 128, h * 128 + 128)]
        assert len(rows) == len(set(rows))
        ops.append({"tensors": [f"model.language_model.layers.{l}.linear_attn.in_proj_z.weight"],
                    "op": "scale", "lam": lam, "layers": [l], "rows": rows,
                    "note": f"L{l}: головы {Z_HEADS[l]} (128 строк на голову)"})
    return ops


H35 = ("H27 (дозировка лучшего математического рычага). Зонд w8: амплитуда |silu(z)| "
       "сосредоточена в 29 головах 13 линейных слоёв (0,12..1,81 по головам). w25 ослабил "
       "именно эти головы в 0,88 раза и дал лучший прирост чисто математического подмножества "
       "за 6 волн: +10 задач против исходной модели (n=300, p=0,27) и 0 против w8, но общий "
       "итог 213/350 из-за потерь формата (FINAL 320 против 332). w31, усиливший те же головы "
       "в 1,06 раза, напротив, отнял 8 задач у w8 (Δмат 0 против исходной). Значит направление "
       "'ослабить доминирующие головы' правильное, а доза 0,88 не обязательно оптимальна. "
       "w35 повторяет w25 доза-в-дозу, но с 0,78: проверка монотонности по математике.")
H36 = ("H28 (разложение дозы w29 по слоям). Накопление 0,93*0,94=0,874 по всем 18 "
       "линейным слоям (w29) дало лучший формат за все волны (FINAL 340/350, обрывов 10 против "
       "18 у w8), но проиграл 11 задач исходной модели и 13 задач w8 на математическом "
       "подмножестве (n=327, p=0,043). Неизвестно, в каких слоях глубокая доза ломает "
       "арифметику. Зонд base->w8: gain_attn упал на 4,1..7,3 % только в поздних линейных слоях "
       "14,16,17,18,20,21,22 — они самые чувствительные к z. w36 добавляет 0,94 только к ним "
       "(итог 0,874 там, 0,93 в остальных). Если математический урон w29 идёт из ранних/средних "
       "слоёв, форматный выигрыш глубокой дозы сохраняется бесплатно.")
H37 = ("H29 (форма дозы по слоям, снятие дозы с ранних слоёв). Уровень 0,93 по всем 18 "
       "слоям (w8) — лучший измеренный math-итог 216/350; уровень 0,874 по всем 18 (w29) — "
       "лучший формат (FINAL 340, обрывов 10) при минусе на математике. Зонд base->w8: "
       "gain_attn упал на 4,1..7,3 % только в поздних слоях 14,16,17,18,20,21,22, а в ранних "
       "он не упал (L2 +3,4 %, L3 +2,3 %, L7 +3,7 %): эффективное действие равномерной дозы "
       "уже сосредоточено в поздних слоях. w37 снимает дозу с 11 ранних и средних линейных "
       "слоёв 0,1,2,4,5,6,8,9,10,12,13 (scale 1,0753, накопительно ~1,00 там, где у w8 было "
       "0,93), оставляя 0,93 в семи поздних. Если ранняя часть дозы не нужна ни математике, "
       "ни формату — вариант не хуже w8; если хуже, равномерность дозы существенна, и семейство "
       "'форма дозы' закрывается с обеих сторон вместе с w36.")

RE = {
    "w35_z_dominant_damp078": {
        "name": "w35_z_dominant_damp078", "hypothesis": H35,
        "expected_effect": ("mean|silu(z)| в 13 слоях с доминирующими головами падает ещё на "
                            "8..12 % относительно w8 (в остальных 5 слоях не меняется); "
                            "mean(exp A_log), dt_bias, beta, q/k-нормы — байт-идентичны w8."),
        "ops": head_ops(0.78)},
    "w36_z_late_extra094": {
        "name": "w36_z_late_extra094", "hypothesis": H36,
        "expected_effect": ("in_proj_z слоёв 14,16,17,18,20,21,22 дополнительно x0,94 "
                            "(накопительно 0,874 против 0,93 у w8); ранние и средние линейные "
                            "слои остаются на 0,93; гейты FULL, A_log, beta не тронуты."),
        "ops": [{"tensors": ["model.language_model.layers.*.linear_attn.in_proj_z.weight"],
                 "op": "scale", "lam": 0.94, "layers": LATE_Z,
                 "note": "7 поздних слоёв, целиком"}]},
    "w37_z_early_release1075": {
        "name": "w37_z_early_release1075", "hypothesis": H37,
        "expected_effect": ("in_proj_z 11 ранних и средних линейных слоёв возвращается к "
                            "значениям исходной модели с точностью округления bf16 "
                            "(0,93 * 1,0753 = 1,00003); семь поздних слоёв остаются на 0,93; "
                            "A_log, dt_bias, beta, q/k-нормы, embed FINAL-строки байт-идентичны w8."),
        "ops": [{"tensors": ["model.language_model.layers.*.linear_attn.in_proj_z.weight"],
                 "op": "scale", "lam": 1.0753, "layers": EARLY_Z,
                 "note": "11 слоёв, целиком; снятие дозы 0,93"}]},
}

for name, r in RE.items():
    p = REC / f"{name}.json"
    p.write_text(json.dumps(r, ensure_ascii=False, indent=1), encoding="utf-8")
    nvals = 0
    if r["name"] == "w35_z_dominant_damp078":
        nvals = sum(len(o["rows"]) for o in r["ops"]) * 1024
    elif r["name"] == "w36_z_late_extra094":
        nvals = len(LATE_Z) * 2048 * 1024
    else:
        nvals = len(EARLY_Z) * 2048 * 1024
    print(f"{name}: ops {len(r['ops'])}  значения {nvals:,}  байты {nvals*2:,}")
    assert EARLY_Z + LATE_Z == LIN
print("доминирующие головы:", {l: Z_HEADS[l] for l in sorted(Z_HEADS)})
