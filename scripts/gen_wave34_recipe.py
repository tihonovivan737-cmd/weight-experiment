#!/usr/bin/env python
"""Генератор рецепта лестницы дозы слоевого рычага ветви `MLP` (журнал §95.5, полосы П85.1 §95.6).

Одно переменное — направление дозы по тензору mlp.up_proj.weight целиком в шести слоях:
Направление ОБРАТНОЕ w83 при той же величине дозы: слои 17, 20, 21 получают
множитель 1,02, слои 14, 15, 23 — обратный 0,9803921568627451.
Суммарная доза по натуральным логарифмам: 3 * ln(1,02) + 3 * ln(1/1,02) = 0.
Это контрольное сравнение направлений гипотезы H58: w83 (то же |дозы|, знак
обратный) дал dev 68, search 147, вместе 215; w84 (доза x2,43, знак как у w83)
дал вместе 205 и ухудшение качества против w8 на 11 задач.

Выбор слоёв взят из измеренных зондов, а не из руки:
  runs/analysis/probe_w8_model.json — gain_mlp в хвосте: слой 14 = 0,5644, слой 15 = 0,6715,
  слой 23 = 0,6427 против слоя 17 = 0,3807, слоя 20 = 0,3266, слоя 21 = 0,3508;
  rms_mlp_branch в хвосте: слой 23 = 0,1890, слой 15 = 0,0596 против слоя 17 = 0,0521.
Опора на неудачу: w44_mlp_branch_late105 поднимал post_attention_layernorm тех же поздних
слоёв множителем 1,05 и потерял математику (205/334/15 против 216/332/18 у w8); здесь те же
слои поднимаются через mlp.up_proj, и это ровно тот контроль, который отличает направление
от случайного сдвига.

Семейство mlp.up_proj тронуто впервые: до волны 32 ни в одном из 78 измеренных
прогонов оно не менялось (w83 — первая точка лестницы).
Рецепт: recipes/w85_mlp_layer_leversign_on_w8.json
База сборки — контрольная точка w8_z_gate_mild_format, читается только на чтение.
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAME = "w85_mlp_layer_leversign_on_w8"
TENSOR = "model.language_model.layers.*.mlp.up_proj.weight"
LAYERS_UP = [17, 20, 21]
LAYERS_DOWN = [14, 15, 23]
LAM_UP = 1.02
LAM_DOWN = 1.0 / LAM_UP
BAND = "П85.1"
PLANNED_BAND = ("dev 56..70 / 88..98 / 0..8; search 138..160 / 220..244 / 8..22; "
                "combined 196..224 / 310..348 / 8..26")


def main():
    ops = [
        {
            "tensors": [TENSOR],
            "op": "scale",
            "lam": LAM_UP,
            "layers": LAYERS_UP,
            "note": "три слоя с высоким относительным вкладом ветви в хвосте "
                    "(gain_mlp 0,5644 / 0,6715 / 0,6427)",
        },
        {
            "tensors": [TENSOR],
            "op": "scale",
            "lam": LAM_DOWN,
            "layers": LAYERS_DOWN,
            "note": "три слоя с большим rms_mlp_branch при малом относительном вкладе "
                    "(gain_mlp 0,3807 / 0,3266 / 0,3508); у w44 поднятие этих слоёв "
                    "стоило 11 задач математики",
        },
    ]
    dose = len(LAYERS_UP) * math.log(LAM_UP) + len(LAYERS_DOWN) * math.log(LAM_DOWN)
    recipe = {
        "name": NAME,
        "hypothesis": "H58: эффект w83_mlp_layer_lever_on_w8 объясняется направлением "
                      "перераспределения мощности ветви mlp.up_proj по слоям, а не самим "
                      "фактом возмущения. В w83 усиливались слои 14, 15, 23 (высокий "
                      "относительный вклад ветви в хвосте: gain_mlp 0,5644 / 0,6715 / "
                      "0,6427) и приглушались 17, 20, 21 (gain_mlp 0,3807 / 0,3266 / "
                      "0,3508); здесь направление обратное при той же величине дозы. "
                      "Ожидание: если направленность реальна, качество w85 упадёт "
                      "относительно w83 не меньше чем на 4 задачи на пересечении строк "
                      "FINAL у обеих моделей; если разница по модулю не превысит 2 задач, "
                      "направленность отвергается и семья рычага слоёв закрывается.",
        "expected_effect": "Сдвиг качества решения на dev и search без изменения профиля "
                           "строки FINAL при сохранении нейтральной суммарной дозы: "
                           "3 * ln(1,02) + 3 * ln(1/1,02) = 0. Ожидаемое изменение норм "
                           "тензора в каждом задетом слое — порядка 2 % на значение; объём "
                           "правки 6 * 3584 * 1024 = 22020096 значений. Точки сравнения: "
                           "w83 (знак обратный, та же величина дозы) — dev 68, search 147, "
                           "вместе 215/331/18; w84 (доза в 2,43 раза больше, знак как у "
                           "w83) — вместе 205/332/16; w8 — вместе 216/332/18. Полоса по "
                           "§95.6: dev 56..70 / 88..98 / 0..8; search 138..160 / 220..244 / "
                           "8..22; combined 196..224 / 310..348 / 8..26. Зачёт: combined "
                           "математика не ниже 217, извлечение не ниже 332, обрывы не "
                           "больше 14, dev математика не ниже 62. Провал: формат ниже 310 "
                           "или математика ниже 196. Решающий критерий — сравнение с w83 на "
                           "пересечении задач с FINAL: разница в пользу w83 от 4 задач "
                           "подтверждает направление, разница в пределах 2 задач — "
                           "опровергает.",
        "band": BAND,
        "ops": ops,
    }
    out = ROOT / "recipes" / f"{NAME}.json"
    if out.exists():
        raise SystemExit(f"файл уже существует, не перезаписываю: {out}")
    out.write_text(json.dumps(recipe, ensure_ascii=False, indent=1), encoding="utf-8")

    rows = sum(3584 for _ in ops)
    print("тип tensors:", "list" if all(isinstance(o["tensors"], list) for o in ops) else "не list")
    print(f"файл: {out.relative_to(ROOT)}, ops {len(ops)}")
    print("строк (по 3584 на операцию):", rows)
    print("планируемых изменённых значений:", rows * 1024)
    print(f"суммарная доза по логарифмам: {dose:+.9f}")
    print("полоса рецепта:", recipe["band"], "— сверена с журналом §95.6")


main()
