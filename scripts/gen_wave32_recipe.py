#!/usr/bin/env python
"""Генератор рецепта слоевого рычага ветви `MLP` (журнал §93.4, полосы П83.1 §93.5).

Одно переменное — направление дозы по тензору mlp.up_proj.weight целиком в шести слоях:
слои 14, 15, 23 получают множитель 1,02, слои 17, 20, 21 — обратный 0,9803921568627451.
Суммарная доза по натуральным логарифмам: 3 * ln(1,02) + 3 * ln(1/1,02) = 0.

Выбор слоёв взят из измеренных зондов, а не из руки:
  runs/analysis/probe_w8_model.json — gain_mlp в хвосте: слой 14 = 0,5644, слой 15 = 0,6715,
  слой 23 = 0,6427 против слоя 17 = 0,3807, слоя 20 = 0,3266, слоя 21 = 0,3508;
  rms_mlp_branch в хвосте: слой 23 = 0,1890, слой 15 = 0,0596 против слоя 17 = 0,0521.
Опора на неудачу: w44_mlp_branch_late105 поднимал post_attention_layernorm тех же поздних
слоёв (включая 17, 20, 21) множителем 1,05 и потерял математику (205/334/15 против 216/332/18
у w8), поэтому здесь эти слои приглушены, а не подняты.

Семейство mlp.up_proj не менялось ни в одном из 77 измеренных прогонов.
Рецепт: recipes/w83_mlp_layer_lever_on_w8.json
База сборки — контрольная точка w8_z_gate_mild_format, читается только на чтение.
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAME = "w83_mlp_layer_lever_on_w8"
TENSOR = "model.language_model.layers.*.mlp.up_proj.weight"
LAYERS_UP = [14, 15, 23]
LAYERS_DOWN = [17, 20, 21]
LAM_UP = 1.02
LAM_DOWN = 1.0 / LAM_UP
BAND = "П83.1"
PLANNED_BAND = ("dev 59..67 / 89..98 / 0..7; search 142..158 / 222..244 / 8..20; "
                "combined 201..221 / 313..346 / 8..24")


def main():
    ops = [
        {
            "tensors": [TENSOR],
            "op": "scale",
            "lam": LAM_UP,
            "layers": LAYERS_UP,
            "note": "три слоя с высоким относительным вкладом ветви в хвосте "
                    "(gain_mlp 0,5644 / 0,6715 / 0,6427)",
        },
        {
            "tensors": [TENSOR],
            "op": "scale",
            "lam": LAM_DOWN,
            "layers": LAYERS_DOWN,
            "note": "три слоя с большим rms_mlp_branch при малом относительном вкладе "
                    "(gain_mlp 0,3807 / 0,3266 / 0,3508); у w44 поднятие этих слоёв "
                    "стоило 11 задач математики",
        },
    ]
    dose = len(LAYERS_UP) * math.log(LAM_UP) + len(LAYERS_DOWN) * math.log(LAM_DOWN)
    recipe = {
        "name": NAME,
        "hypothesis": "H56: арифметическое качество определяется распределением мощности "
                      "ветви mlp.up_proj по слоям, а не уровнем гейта внимания. При точечно "
                      "нейтральной суммарной дозе (3 слоя x1,02 против 3 слоёв x0,980392) "
                      "усиливаются слои с высоким относительным вкладом ветви в хвосте "
                      "генерации и приглушаются слои, где ветвь велика, а относительный "
                      "вклад мал.",
        "expected_effect": "Сдвиг качества решения на dev и search без изменения профиля "
                           "строки FINAL. Суммарная доза по логарифмам равна "
                           f"{dose:+.6f}, то есть ноль; меняются только относительные доли "
                           "между слоями. Ожидаемое изменение нормы тензора в каждом "
                           "задетом слое — порядка 2 % на значение; доля правки симметрична по дозе "
                           "между слоями. Объём правки: 6 * 3584 * 1024 = 22020096 "
                           "значений. Полоса по §93.5: " + PLANNED_BAND + ". Условие зачёта: "
                           "combined математика не ниже 217, извлечение не ниже 332, обрывы "
                           "не больше 14, dev математика не ниже 62. Провал: формат ниже 313 "
                           "или математика ниже 201.",
        "band": BAND,
        "ops": ops,
    }
    out = ROOT / "recipes" / f"{NAME}.json"
    if out.exists():
        raise SystemExit(f"файл уже существует, не перезаписываю: {out}")
    out.write_text(json.dumps(recipe, ensure_ascii=False, indent=1), encoding="utf-8")

    rows = sum(3584 for _ in ops)
    print("тип tensors:", "list" if all(isinstance(o["tensors"], list) for o in ops) else "не list")
    print(f"файл: {out.relative_to(ROOT)}, ops {len(ops)}")
    print("строк (по 3584 на операцию):", rows)
    print("планируемых изменённых значений:", rows * 1024)
    print(f"суммарная доза по логарифмам: {dose:+.9f}")
    print("полоса рецепта:", recipe["band"], "— сверена с журналом §93.5")


main()
